function rubyPairToStyle(base, ruby, target) {
  switch (target) {
    case "none":
      return base + "\u300A" + ruby + "\u300B";
    case "remove":
      return base;
    case "narou":
      return "|" + base + "\u300A" + ruby + "\u300B";
    case "aozora":
      return "\uFF5C" + base + "\u300A" + ruby + "\u300B";
    case "denden":
      return "{" + base + "|" + ruby + "}";
    case "html":
      return "<ruby>" + base + "<rt>" + ruby + "</rt></ruby>";
  }
}
function convertRubyStyle(text, sourceStyle, target) {
  if (target === "none") return text;
  const matches = findRubyMatches(text, sourceStyle);
  if (matches.length === 0) return text;
  let result = "";
  let cursor = 0;
  for (const m of matches) {
    result += text.slice(cursor, m.from);
    result += rubyPairToStyle(m.base, m.ruby, target);
    cursor = m.to;
  }
  result += text.slice(cursor);
  return result;
}
