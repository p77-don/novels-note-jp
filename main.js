  /**
   * 用語インデックスを再構築する。
   * 戻り値は「実際に用語リストの内容が変化したかどうか」。
   * 呼び出し元はこれを見て、変化がなければ updateSidebar() /
   * refreshEditors() をスキップできる（詳細は scheduleRebuild() 参照）。
   */
  async buildTermIndex() {
    var _a;
    const previousTerms = this.terms;
    this.terms = [];
    const validTags = new Set(this.settings.tagDefinitions.map((td) => td.tag));
    const files = this.app.vault.getMarkdownFiles();
    const excludedPrefixes = ((_a = this.settings.excludeFolders) != null ? _a : []).map((f) => f.trim()).filter((f) => f.length > 0).map((f) => f.endsWith("/") ? f : f + "/");
    for (const file of files) {
      if (excludedPrefixes.some((prefix) => file.path.startsWith(prefix))) continue;
      const cache = this.app.metadataCache.getFileCache(file);
      if (!(cache == null ? void 0 : cache.frontmatter)) continue;
      const fm = cache.frontmatter;
      let tags = [];
      if (Array.isArray(fm.tags)) {
        tags = fm.tags.map((t) => String(t).replace(/^#/, ""));
      } else if (typeof fm.tags === "string") {
        tags = [fm.tags.replace(/^#/, "")];
      }
      const matchedTag = tags.find((t) => validTags.has(t));
      if (!matchedTag) continue;
      const name = typeof fm.name === "string" && fm.name.trim() !== "" ? fm.name.trim() : file.basename;
      let aliases = [];
      if (Array.isArray(fm.aliases)) {
        aliases = fm.aliases.map((a) => String(a));
      } else if (typeof fm.aliases === "string") {
        aliases = [fm.aliases];
      }
      this.terms.push({ name, aliases, tag: matchedTag, filePath: file.path });
    }
    this.terms.sort((a, b) => b.name.length - a.name.length);
    return !areTermListsEqual(previousTerms, this.terms);
  }
